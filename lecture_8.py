rows = []
for col in num_cols:
    Q1 = raw[col].quantile(0.25)
    Q3 = raw[col].quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    count = ((raw[col] < lower) | (raw[col] > upper)).sum()
    rows.append([col, round(lower, 1), round(upper, 1), count])

outlier_table = pd.DataFrame(rows, columns=["Variable", "Lower Fence", "Upper Fence", "Outliers Found"])
outlier_table

