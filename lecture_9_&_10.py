"""how much does a raining hurt delievery time and rating in each state"""

means = df.groupby(["State", "Weather"])[
    ["Delivery_Time_Min", "Customer_Rating"]
].mean().reset_index()

clear = means[means["Weather"] == "Clear"].set_index("State")
rain = means[means["Weather"] == "Rain"].set_index("State")

# Starting points: Clear weather
x = clear["Delivery_Time_Min"]
y = clear["Customer_Rating"]

# Changes during rainy weather
dx = rain["Delivery_Time_Min"] - clear["Delivery_Time_Min"]
dy = rain["Customer_Rating"] - clear["Customer_Rating"]
# Create the arrow chart
plt.figure(figsize=(8, 5))

plt.quiver(
    x, y, dx, dy,
    angles="xy",
    scale_units="xy",
    scale=1,
    color="#6A1B9A"
)

plt.scatter(x, y, color="grey")

# Add state names at the end of each arrow
for name in clear.index:
    plt.text(
        x[name] + dx[name],
        y[name] + dy[name] - 0.03,
        name,
        fontsize=7
    )

# Configure chart limits
plt.xlim(x.min() - 1, (x + dx).max() + 2)
plt.ylim((y + dy).min() - 0.15, y.max() + 0.1)

# Add title and axis labels
plt.title("Impact of Rain on Delivery Time and Customer Rating")
plt.xlabel("Average Delivery Time (minutes)")
plt.ylabel("Average Customer Rating")

plt.grid(alpha=0.3)
plt.show()

